create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text not null,
  location text,
  target_role text,
  experience_level text,
  skills jsonb not null default '[]'::jsonb,
  resume_state jsonb not null default '{}'::jsonb,
  selected_career_id text,
  skill_gap jsonb,
  recommendations jsonb,
  assessment_result jsonb,
  confidence numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists skills jsonb not null default '[]'::jsonb;
alter table public.profiles add column if not exists resume_state jsonb not null default '{}'::jsonb;
alter table public.profiles add column if not exists selected_career_id text;
alter table public.profiles add column if not exists skill_gap jsonb;
alter table public.profiles add column if not exists recommendations jsonb;
alter table public.profiles add column if not exists assessment_result jsonb;
alter table public.profiles add column if not exists confidence numeric;

alter table public.profiles enable row level security;

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_type text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.activity_logs enable row level security;

-- PostgreSQL has no CREATE POLICY IF NOT EXISTS. These checks preserve any
-- policies that already exist and create only missing policies.
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'activity_logs'
      and policyname = 'Users can view their own activity'
  ) then
    create policy "Users can view their own activity"
      on public.activity_logs for select using (auth.uid() = user_id);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'activity_logs'
      and policyname = 'Users can create their own activity'
  ) then
    create policy "Users can create their own activity"
      on public.activity_logs for insert with check (auth.uid() = user_id);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'profiles'
      and policyname = 'Users can view their own profile'
  ) then
    create policy "Users can view their own profile"
      on public.profiles for select using (auth.uid() = id);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'profiles'
      and policyname = 'Users can create their own profile'
  ) then
    create policy "Users can create their own profile"
      on public.profiles for insert with check (auth.uid() = id);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'profiles'
      and policyname = 'Users can update their own profile'
  ) then
    create policy "Users can update their own profile"
      on public.profiles for update
      using (auth.uid() = id)
      with check (auth.uid() = id);
  end if;
end
$$;

insert into storage.buckets (id, name, public)
values ('resumes', 'resumes', false)
on conflict (id) do nothing;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Users can upload resumes into their own folder'
  ) then
    create policy "Users can upload resumes into their own folder"
      on storage.objects for insert
      with check (
        bucket_id = 'resumes'
        and (storage.foldername(name))[1] = (select auth.uid()::text)
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Users can view their own resumes'
  ) then
    create policy "Users can view their own resumes"
      on storage.objects for select
      using (
        bucket_id = 'resumes'
        and (storage.foldername(name))[1] = (select auth.uid()::text)
      );
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Users can delete their own resumes'
  ) then
    create policy "Users can delete their own resumes"
      on storage.objects for delete
      using (
        bucket_id = 'resumes'
        and (storage.foldername(name))[1] = (select auth.uid()::text)
      );
  end if;
end
$$;

